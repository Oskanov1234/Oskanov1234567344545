let today = new Date()
console.log(today);

console.log(today.getDate()); // число
console.log(today.getDay()); // день
console.log(today.getFullYear()); // год
console.log(today.getHours()); // час
console.log(today.getMilliseconds()); // миллесикунды
console.log(today.getMinutes()); // минуты
console.log(today.getMonth()); // месяц
console.log(today.getSeconds()); // секунды
console.log(today.getTime()); // время с 1970 года
console.log(today.getTimezoneOffset()); // сколько дней прошло со всего года
console.log(today.getUTCDate()); // день по часовому поясу
console.log(today.getUTCDay()); // день по часовому поясу
console.log(today.getUTCFullYear()); // год по часовому поясу
console.log(today.getUTCHours()); // час по часовому поясу
console.log(today.getUTCMilliseconds()); // миллесекунды по часовому поясу
console.log(today.getUTCMinutes()); // минуты по часовому поясу
console.log(today.getUTCMonth()); // месяц по часовому поясу 
console.log(today.getUTCSeconds()); // секунды по часовому поясу
